#!/usr/bin/env python3
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from unittest.mock import patch

from scripts.sync import choose_match, normalize, split_sections, sync_sources  # noqa: E402


class SyncTests(unittest.TestCase):
    def test_split_sections_keeps_nested_bullets(self):
        text = """# Skill
## Topic A
- one
### Detail
- two
## Topic B
- three
"""
        sections = split_sections(text)
        self.assertEqual(sections["Topic A"], ["one", "two"])
        self.assertEqual(sections["Topic B"], ["three"])

    def test_normalize_ignores_case_punctuation_and_spacing(self):
        self.assertEqual(normalize("Do  NOT edit this file."), "do not edit this file")

    def test_exact_match(self):
        rules = [{"id": "a", "text": "State your assumptions explicitly. If uncertain, ask."}]
        rule, score, kind = choose_match("State your assumptions explicitly. If uncertain, ask.", rules)
        self.assertEqual(kind, "exact")
        self.assertEqual(rule["id"], "a")
        self.assertEqual(score, 1.0)

    def test_fuzzy_match(self):
        rules = [{"id": "a", "text": "State your assumptions explicitly. If uncertain, ask."}]
        rule, score, kind = choose_match("State your assumptions explicitly. If unsure, ask.", rules)
        self.assertEqual(kind, "fuzzy")
        self.assertEqual(rule["id"], "a")
        self.assertGreaterEqual(score, 0.90)

    def test_negation_is_not_auto_merged(self):
        rules = [{"id": "a", "text": "Do not remove pre-existing dead code unless asked."}]
        rule, score, kind = choose_match("Remove pre-existing dead code unless asked.", rules)
        self.assertEqual(kind, "possible")
        self.assertEqual(rule["id"], "a")

    def test_supersedes_matches_the_bullet_a_rule_replaces(self):
        rules = [{
            "id": "a",
            "text": "Commit or push only when the user explicitly asks.",
            "supersedes": ["Commit often, in small ordered commits."],
        }]
        rule, score, kind = choose_match("Commit often, in small ordered commits.", rules)
        self.assertEqual(kind, "superseded")
        self.assertEqual(rule["id"], "a")
        self.assertEqual(score, 1.0)


if __name__ == "__main__":
    unittest.main()

class SyncPipelineTests(unittest.TestCase):
    def _config(self):
        return {
            "skill": {
                "name": "coding-discipline",
                "description": "x",
                "license": "MIT",
                "metadata": {"version": "1.0.0"},
            },
            "intro": ["intro"],
            "sections": [{
                "id": "s", "title": "Section",
                "groups": [{
                    "id": "g", "title": "Group",
                    "source_headings": [{"source": "fake", "heading": "Topic"}],
                    "rules": [{"id": "existing", "text": "Keep changes small."}],
                }],
            }],
            "outro": [],
        }

    def _sources(self):
        return [{
            "id": "fake", "repo": "example/fake", "path": "SKILL.md",
            "ref": "main", "license": "MIT", "headings": {"Topic": "g"},
        }]

    @patch("scripts.sync.fetch_text", return_value="# Fake\n## Topic\n- Keep changes small.\n- New rule.\n")
    @patch("scripts.sync.latest_commit", return_value="a" * 40)
    def test_new_bullet_is_appended(self, _commit, _fetch):
        config, lock, coverage = sync_sources(self._config(), self._sources())
        rules = config["sections"][0]["groups"][0]["rules"]
        self.assertEqual(len(rules), 2)
        self.assertTrue(rules[1]["auto"])
        self.assertEqual(coverage["new"], 1)

    @patch("scripts.sync.fetch_text", return_value="# Fake\n## Topic\n- Keep changes small.\n")
    @patch("scripts.sync.latest_commit", return_value="a" * 40)
    def test_existing_bullet_is_not_duplicated(self, _commit, _fetch):
        config, lock, coverage = sync_sources(self._config(), self._sources())
        rules = config["sections"][0]["groups"][0]["rules"]
        self.assertEqual(len(rules), 1)
        self.assertEqual(coverage["matched"], 1)
        self.assertEqual(coverage["new"], 0)


if __name__ == "__main__":
    unittest.main()
